package B_MemoriaArrayListas.Exercicios.Entities;

public class Exercicio10 {
    private String nome;
    private int idade;

    public Exercicio10() {
    }

    public Exercicio10(String nome, int idade) {
        this.nome = nome;
        this.idade = idade;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public int getIdade() {
        return idade;
    }

    public void setIdade(int idade) {
        this.idade = idade;
    }
}
